import { GoogleGenAI } from '@google/genai';
import { supabaseAdmin } from '../config/supabase.js';
import { env } from '../config/env.js';
import { logger } from '../utils/logger.js';
import pdfParseModule from 'pdf-parse';
const pdfParse: any = (pdfParseModule as any).default || pdfParseModule;

export class InProcessAiWorker {
  private isRunning = false;
  private timer: NodeJS.Timeout | null = null;
  private workerId = `node-worker-${process.pid}`;
  private ai: GoogleGenAI | null = null;

  constructor() {
    if (env.GEMINI_API_KEY) {
      this.ai = new GoogleGenAI({ apiKey: env.GEMINI_API_KEY });
    }
  }

  public start() {
    if (this.isRunning) return;
    if (!env.ENABLE_IN_PROCESS_AI_WORKER) {
      logger.info('In-process AI worker disabled via ENABLE_IN_PROCESS_AI_WORKER=false');
      return;
    }
    if (!env.GEMINI_API_KEY) {
      logger.warn('In-process AI worker skipped: GEMINI_API_KEY not configured in backend env');
      return;
    }

    this.isRunning = true;
    logger.info(`Starting In-Process AI Worker daemon [${this.workerId}]`);
    this.poll();
  }

  public stop() {
    this.isRunning = false;
    if (this.timer) {
      clearTimeout(this.timer);
      this.timer = null;
    }
    logger.info('In-Process AI Worker stopped');
  }

  private async poll() {
    if (!this.isRunning) return;

    try {
      await this.processNextJob();
    } catch (err: any) {
      logger.error('Error during in-process worker poll', { error: err.message });
    } finally {
      if (this.isRunning) {
        this.timer = setTimeout(() => this.poll(), 5000);
      }
    }
  }

  private async processNextJob() {
    // Claim next queued job atomically via Supabase RPC
    const { data: claimed, error: claimErr } = await supabaseAdmin.rpc('claim_next_document_job', {
      p_worker_id: this.workerId,
      p_stale_minutes: 20
    });

    if (claimErr || !claimed || claimed.length === 0) {
      return; // No jobs queued
    }

    const job = claimed[0];
    logger.info(`Claimed document job ${job.id} for document ${job.document_id}`, { stage: 'claimed' });

    try {
      await this.executeJob(job);
    } catch (err: any) {
      logger.error(`Job ${job.id} processing failed: ${err.message}`, { job_id: job.id });
      await supabaseAdmin.from('document_jobs').update({
        status: 'failed',
        current_stage: 'failed',
        last_error_code: 'ERR_PROCESSING',
        last_error_message: err.message || 'Unknown processing error',
        completed_at: new Date().toISOString()
      }).eq('id', job.id);

      await supabaseAdmin.from('documents').update({
        processing_status: 'failed'
      }).eq('id', job.document_id);
    }
  }

  private async executeJob(job: any) {
    const docId = job.document_id;
    const userId = job.user_id;

    // 1. Fetch document metadata
    const { data: doc, error: docErr } = await supabaseAdmin
      .from('documents')
      .select('*')
      .eq('id', docId)
      .single();

    if (docErr || !doc) {
      throw new Error(`Document ${docId} metadata not found`);
    }

    // 2. Download file buffer from private Supabase Storage
    const { data: fileBlob, error: downloadErr } = await supabaseAdmin
      .storage
      .from('documents')
      .download(doc.storage_path);

    if (downloadErr || !fileBlob) {
      throw new Error(`Failed to download file from storage: ${downloadErr?.message}`);
    }

    const arrayBuffer = await fileBlob.arrayBuffer();
    const buffer = Buffer.from(arrayBuffer);

    // 3. Extract text content
    let extractedText = '';
    let pageCount = 1;

    if (doc.mime_type === 'application/pdf') {
      try {
        const parsed = await pdfParse(buffer);
        extractedText = parsed.text || '';
        pageCount = parsed.numpages || 1;
      } catch (e: any) {
        logger.warn(`pdf-parse failed on ${doc.safe_filename}: ${e.message}`);
      }
    }

    // 4. Send to Gemini for classification, structured extraction, and summary
    const aiResult = await this.callGemini(doc, buffer, extractedText);

    // 5. Save structured data in PostgreSQL
    const category = aiResult.category || doc.category || 'unknown';

    // Update document
    await supabaseAdmin.from('documents').update({
      category: category,
      page_count: pageCount,
      processing_status: 'completed',
      confidence_score: aiResult.confidence_score || 0.95,
      summary: aiResult.summary || 'Summary generated by VeriDoc AI',
      processed_at: new Date().toISOString()
    }).eq('id', docId);

    // Upsert document_extractions
    await supabaseAdmin.from('document_extractions').upsert({
      document_id: docId,
      user_id: userId,
      category: category,
      extracted_data: aiResult.extracted_data || {},
      schema_version: '1.0',
      model_name: env.GEMINI_MODEL || 'gemini-3.8-flash',
      confidence_score: aiResult.confidence_score || 0.95
    }, { onConflict: 'document_id' });

    // Upsert verification_records
    await supabaseAdmin.from('verification_records').upsert({
      document_id: docId,
      user_id: userId,
      status: 'pending',
      original_data: aiResult.extracted_data || {},
      corrected_data: aiResult.extracted_data || {}
    }, { onConflict: 'document_id' });

    // Insert chunks if any
    if (aiResult.chunks && aiResult.chunks.length > 0) {
      const chunkRows = aiResult.chunks.map((c: any, idx: number) => ({
        document_id: docId,
        user_id: userId,
        chunk_index: idx,
        page_start: c.page_start || 1,
        page_end: c.page_end || 1,
        chunk_text: c.text || '',
        chunk_summary: c.summary || ''
      }));
      await supabaseAdmin.from('document_chunks').upsert(chunkRows, { onConflict: 'document_id,chunk_index' });
    }

    // Mark job as completed
    await supabaseAdmin.from('document_jobs').update({
      status: 'completed',
      current_stage: 'completed',
      completed_at: new Date().toISOString()
    }).eq('id', job.id);

    logger.info(`Successfully completed document job ${job.id} for document ${docId}`);
  }

  private async callGemini(doc: any, buffer: Buffer, extractedText: string): Promise<any> {
    if (!this.ai) {
      throw new Error('Gemini client not initialized. Check GEMINI_API_KEY');
    }

    const model = env.GEMINI_MODEL || 'gemini-3.8-flash';

    const systemPrompt = `You are VeriDoc AI, an enterprise-grade document extraction model.
You analyze business documents (Invoices, Bank Statements, Purchase Orders, Large PDF Documents).
You must output strictly valid JSON matching this schema:
{
  "category": "invoices" | "bank_statements" | "purchase_orders" | "large_pdf_documents" | "unknown",
  "confidence_score": 0.98,
  "summary": "Detailed executive summary of the document",
  "extracted_data": {
    // If invoice:
    "invoice_number": "string",
    "invoice_date": "YYYY-MM-DD",
    "due_date": "YYYY-MM-DD",
    "vendor_name": "string",
    "vendor_address": "string",
    "customer_name": "string",
    "total_amount": 0.0,
    "tax_amount": 0.0,
    "subtotal": 0.0,
    "currency": "USD",
    "line_items": [{"description": "item", "quantity": 1, "unit_price": 10.0, "line_total": 10.0}]

    // If bank statement:
    "bank_name": "string",
    "account_holder": "string",
    "masked_account_number": "XXXX-1234",
    "opening_balance": 0.0,
    "closing_balance": 0.0,
    "transactions": [{"transaction_date": "YYYY-MM-DD", "description": "str", "debit_amount": 0.0, "credit_amount": 0.0, "running_balance": 0.0}]

    // If purchase order:
    "po_number": "string",
    "po_date": "YYYY-MM-DD",
    "buyer_company": "string",
    "supplier_company": "string",
    "grand_total": 0.0,
    "line_items": [{"description": "item", "quantity": 1, "unit_price": 10.0, "line_total": 10.0}]

    // If large PDF document:
    "title": "string",
    "key_topics": ["topic1", "topic2"],
    "key_entities": ["entity1"],
    "action_items": ["item1"]
  },
  "chunks": [
    {"page_start": 1, "page_end": 1, "text": "sample text", "summary": "chunk summary"}
  ]
}
Return only the raw JSON. No markdown backticks, no explanations.`;

    const contents: any[] = [];

    // If text was extracted, include it in prompt
    if (extractedText && extractedText.trim().length > 30) {
      contents.push({
        text: `Filename: ${doc.original_filename}\nExtracted text content:\n${extractedText.substring(0, 15000)}`
      });
    } else {
      // Pass file directly as inline data
      contents.push({
        inlineData: {
          mimeType: doc.mime_type,
          data: buffer.toString('base64')
        }
      });
      contents.push({
        text: `Filename: ${doc.original_filename}. Extract and classify this document.`
      });
    }

    const response = await this.ai.models.generateContent({
      model: model,
      contents: contents,
      config: {
        systemInstruction: systemPrompt,
        responseMimeType: 'application/json'
      }
    });

    const text = response.text || '{}';
    try {
      return JSON.parse(text);
    } catch {
      // Clean possible markdown code fences
      const cleaned = text.replace(/```json/g, '').replace(/```/g, '').trim();
      return JSON.parse(cleaned);
    }
  }
}

export const inProcessAiWorker = new InProcessAiWorker();
